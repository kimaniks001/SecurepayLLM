export function errorText(error: unknown): string {
  if (error instanceof ApiError) {
    if (error.kind === 'network' || error.kind === 'timeout' || (error.status ?? 0) >= 500) return 'SecurePay is unavailable. Please try again.';
    return error.message;
  }
  return 'SecurePay could not complete this step. Please try again.';
}
function asApiError(error: unknown): ApiError {
  return error instanceof ApiError ? error : new ApiError('network', 'SecurePay is unavailable');
}
function newIdempotencyKey(prefix: string): string {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}
/**
 * Correction (Slice 2, second pre-merge pass) -- mirrors the backend's own KS Number normalization
 * (`TrustProjectMembershipService#normalizeKsNumber`: trim + uppercase) so the frontend's own "is
 * this the same target the key is already bound to" comparison agrees with what the backend
 * considers the same invitee, never a stricter or looser rule of its own.
 */
function normalizeKsNumberForComparison(value: string): string {
  return value.trim().toUpperCase();
}

